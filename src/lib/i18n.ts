export type DictKey = keyof typeof dict.zh;

export function translate(lang: Lang, key: DictKey): string {
  return dict[lang][key] ?? key;
}

/// 模板替换：translate("monitor_pts", { visible: 12, total: 600 })
/// 占位符形如 `{name}`，未在 params 中找到的占位符保持原样。
export function translateWith(
  lang: Lang,
  key: DictKey,
  params: Record<string, string | number>,
): string {
  const raw = translate(lang, key);
  return raw.replace(/\{(\w+)\}/g, (m, k) => {
    const v = params[k];
    return v === undefined || v === null ? m : String(v);
  });
}
